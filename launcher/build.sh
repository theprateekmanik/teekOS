#!/bin/zsh
# Builds teekOS with the bare SDK tools (no Gradle).
#   ./build.sh            your build  -> teekOS.apk        (name from TEEKOS_NAME, default "Teek"; PS5 tile always)
#   SHARE=1 ./build.sh    share build -> teekOS-share.apk  (no name; PS5 tile only if a console is detected)
# Signing: keystore ~/.android/teekos.keystore, password in ~/.android/teekos.keystore.pass
# (or TEEKOS_KS_PASS). Missing keystore: a new one is created on first build.
set -e
cd "${0:A:h}"
export JAVA_HOME=/opt/homebrew/opt/openjdk@17 PATH=/opt/homebrew/opt/openjdk@17/bin:$PATH
SDK=${ANDROID_HOME:-$HOME/Library/Android/sdk}; BT=$SDK/build-tools/34.0.0; JAR=$SDK/platforms/android-34/android.jar
if [[ -n "$SHARE" ]]; then NAME=""; PS=false; OUT=teekOS-share.apk; else NAME=${TEEKOS_NAME-Teek}; PS=true; OUT=teekOS.apk; fi
rm -rf build; mkdir -p build/gen/space/teek/tvos build/obj build/dex
cat > build/gen/space/teek/tvos/Owner.java <<JAVA
package space.teek.tvos;
/** Generated by build.sh: who this build is for. */
final class Owner {
    private Owner() { }
    static final String NAME = "$NAME";
    static final boolean PS_ALWAYS = $PS;
}
JAVA
$BT/aapt2 compile --dir res -o build/res.zip
$BT/aapt2 link -I $JAR --manifest AndroidManifest.xml --java build/gen \
  --min-sdk-version 26 --target-sdk-version 30 -A assets -o build/unsigned.apk build/res.zip
javac -nowarn --release 11 -classpath $JAR -d build/obj $(find src build/gen -name '*.java')
$BT/d8 --release --min-api 26 --lib $JAR --output build/dex $(find build/obj -name '*.class')
(cd build/dex && zip -q ../unsigned.apk classes.dex)
$BT/zipalign -f 4 build/unsigned.apk build/aligned.apk
KS=$HOME/.android/teekos.keystore
PASS=${TEEKOS_KS_PASS:-$(cat $HOME/.android/teekos.keystore.pass 2>/dev/null)}
[[ -n "$PASS" ]] || { echo "Set TEEKOS_KS_PASS or create ~/.android/teekos.keystore.pass"; exit 1; }
[[ -f $KS ]] || keytool -genkeypair -keystore $KS -storepass "$PASS" -keypass "$PASS" -alias teekos \
  -keyalg RSA -keysize 2048 -validity 10000 -dname "CN=teekOS" >/dev/null 2>&1
$BT/apksigner sign --ks $KS --ks-pass pass:$PASS --out $OUT build/aligned.apk
echo "built $(du -h $OUT | cut -f1) $OUT"
